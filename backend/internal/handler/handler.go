// deleteTask godoc
// @Summary      Delete a task
// @Tags         Admin
// @Security     ApiKeyAuth
// @Param        X-User-ID    header    string  true  "Admin User ID"
// @Param        choregroupID path      string  true  "ChoreGroup ID"
